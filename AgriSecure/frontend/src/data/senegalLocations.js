// Fonction pour obtenir toutes les communes
export const getAllCommunes = () => {
  const communes = []
  SENEGAL_REGIONS.forEach(region => {
    region.departments.forEach(dept => {
      dept.communes.forEach(commune => {
        communes.push({
          ...commune,
          department: dept.name,
          region: region.name,
          regionCode: region.code
        })
      })
    })
  })
  return communes
}

// Fonction pour rechercher une commune
export const searchCommune = (query) => {
  if (!query || query.trim().length < 2) return []

  const searchTerm = query.toLowerCase().trim()
  const allCommunes = getAllCommunes()

  return allCommunes.filter(commune =>
    commune.name.toLowerCase().includes(searchTerm) ||
    commune.department.toLowerCase().includes(searchTerm) ||
    commune.region.toLowerCase().includes(searchTerm)
  ).slice(0, 20) // Limiter à 20 résultats
}

// Fonction pour obtenir les communes d'une région
export const getCommunesByRegion = (regionName) => {
  const region = SENEGAL_REGIONS.find(r => r.name === regionName)
  if (!region) return []

  const communes = []
  region.departments.forEach(dept => {
    dept.communes.forEach(commune => {
      communes.push({
        ...commune,
        department: dept.name,
        region: region.name
      })
    })
  })
  return communes
}

// Fonction pour obtenir les coordonnées d'une commune
export const getCommuneGPS = (communeName, regionName) => {
  const region = SENEGAL_REGIONS.find(r => r.name === regionName)
  if (!region) return null

  for (const dept of region.departments) {
    const commune = dept.communes.find(c => c.name === communeName)
    if (commune) return commune.gps
  }

  return null
}

// Format téléphone sénégalais
export const formatSenegalPhone = (phone) => {
  // Enlever espaces et caractères spéciaux
  const cleaned = phone.replace(/\D/g, '')

  // Si commence par 221, c'est déjà avec indicatif
  if (cleaned.startsWith('221')) {
    const number = cleaned.substring(3)
    if (number.length === 9) {
      return `+221 ${number.substring(0, 2)} ${number.substring(2, 5)} ${number.substring(5, 7)} ${number.substring(7, 9)}`
    }
  }

  // Sinon, ajouter +221
  if (cleaned.length === 9) {
    return `+221 ${cleaned.substring(0, 2)} ${cleaned.substring(2, 5)} ${cleaned.substring(5, 7)} ${cleaned.substring(7, 9)}`
  }

  return phone
}

// Validation téléphone sénégalais
export const isValidSenegalPhone = (phone) => {
  const cleaned = phone.replace(/\D/g, '')

  // Avec indicatif: +221 XX XXX XX XX (12 chiffres)
  if (cleaned.startsWith('221') && cleaned.length === 12) {
    const prefix = cleaned.substring(3, 5)
    return ['77', '78', '76', '70', '75'].includes(prefix)
  }

  // Sans indicatif: XX XXX XX XX (9 chiffres)
  if (cleaned.length === 9) {
    const prefix = cleaned.substring(0, 2)
    return ['77', '78', '76', '70', '75'].includes(prefix)
  }

  return false
}

// Fonction pour calculer distance entre 2 points GPS (formule Haversine)
const getDistanceFromLatLng = (lat1, lng1, lat2, lng2) => {
  const R = 6371 // Rayon de la Terre en km
  const dLat = (lat2 - lat1) * Math.PI / 180
  const dLng = (lng2 - lng1) * Math.PI / 180
  const a =
    Math.sin(dLat / 2) * Math.sin(dLat / 2) +
    Math.cos(lat1 * Math.PI / 180) * Math.cos(lat2 * Math.PI / 180) *
    Math.sin(dLng / 2) * Math.sin(dLng / 2)
  const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a))
  const distance = R * c // Distance en km
  return distance
}

// Trouver la commune la plus proche d'une position GPS
export const findCommuneByGPS = (lat, lng, maxDistance = 50) => {
  const allCommunes = getAllCommunes()

  let nearest = null
  let minDistance = Infinity

  allCommunes.forEach(commune => {
    if (commune.gps) {
      const distance = getDistanceFromLatLng(lat, lng, commune.gps.lat, commune.gps.lng)
      if (distance < minDistance && distance <= maxDistance) {
        minDistance = distance
        nearest = {
          ...commune,
          distance: distance.toFixed(2) // Distance en km
        }
      }
    }
  })

  return nearest
}
